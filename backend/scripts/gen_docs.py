"""Generate docs/generated/*.md from the registries. Never hand-edit the outputs.

Usage (from backend/):  python scripts/gen_docs.py [--check]
--check exits 1 when the committed files differ from what the registries produce.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "generated"
sys.path.insert(0, str(ROOT / "backend"))

from app.agents.builtin import build_evaluators, build_registry  # noqa: E402
from app.api.declare import RATE_LIMITS  # noqa: E402
from app.api.routes import api  # noqa: E402
from app.domain import slots as slot_registry  # noqa: E402

HEADER = "<!-- GENERATED by backend/scripts/gen_docs.py. Do not edit by hand. -->\n\n"


def tools_md() -> str:
    reg = build_registry()
    rows = ["# Tools\n", "| name | v | description | side effect | credits | timeout s | agents |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in reg.tools():
        m = t.meta
        agents = ", ".join(a.key for a in reg.agents() if m.name in a.tool_names)
        rows.append(
            f"| `{m.name}` | {m.version} | {m.description} | {m.side_effect} | "
            f"{m.cost_credits} | {m.timeout_s:g} | {agents} |"
        )
    for t in reg.tools():
        props = t.input_schema().get("properties", {})
        rows += [f"\n## `{t.meta.name}` input", "", "| field | type |", "| --- | --- |"]
        for k, v in props.items():
            rows.append(f"| `{k}` | {v.get('type') or v.get('anyOf') or v.get('$ref', '')} |")
    return "\n".join(rows) + "\n"


def skills_md() -> str:
    reg = build_registry()
    rows = ["# Skills\n", "| id | audience | description | hash | agents |",
            "| --- | --- | --- | --- | --- |"]
    for s in reg.skills():
        agents = ", ".join(a.key for a in reg.agents() if s.id in a.skill_ids)
        rows.append(
            f"| `{s.id}` | {s.audience} | {s.description} | `{s.content_hash}` | {agents} |"
        )
    return "\n".join(rows) + "\n"


def agents_md() -> str:
    reg = build_registry()
    rows = ["# Agents\n", "| key | workbench | task kind | artifact kinds | tools | skills |",
            "| --- | --- | --- | --- | --- | --- |"]
    for a in reg.agents():
        rows.append(
            f"| `{a.key}` | {a.workbench} | {a.task_kind or '-'} | {', '.join(a.artifact_kinds)} | "
            f"{', '.join(a.tool_names)} | {', '.join(a.skill_ids)} |"
        )
    return "\n".join(rows) + "\n"


def evaluators_md() -> str:
    rows = ["# Evaluators\n", "| id | type | can reject | description |", "| --- | --- | --- | --- |"]
    for e in build_evaluators().all():
        rows.append(f"| `{e.id}` | rule | {e.can_reject} | {e.description} |")
    return "\n".join(rows) + "\n"


def slots_md() -> str:
    rows = ["# Slots\n", "| key | value type | artifact kind | max items | description |",
            "| --- | --- | --- | --- | --- |"]
    for s in slot_registry.all_slots():
        rows.append(
            f"| `{s.key}` | {s.value_type} | {s.artifact_kind} | {s.max_items} | {s.description} |"
        )
    rows += ["", "Task kinds: " + ", ".join(
        f"`{k}` -> {', '.join(slot_registry.slots_for_task_kind(k)) or _no_fixed_slots(k)}"
        for k in slot_registry.task_kinds())]
    return "\n".join(rows) + "\n"


def _no_fixed_slots(kind: str) -> str:
    if kind == "general":
        return "files from write_file, image, or canvas"
    return "file names from write_file"


def api_md() -> str:
    rows = ["# API\n", "| method | path | auth | rate class |", "| --- | --- | --- | --- |"]
    for d in sorted(api.decls, key=lambda d: (d.path, d.method)):
        rows.append(f"| {d.method} | `{d.path}` | {'yes' if d.auth else 'no'} | {d.rate} |")
    rows += ["", "Rate classes: " + ", ".join(
        f"`{k}` {n}/{int(w)}s" for k, (n, w) in RATE_LIMITS.items())]
    return "\n".join(rows) + "\n"


FILES = {
    "tools.md": tools_md, "skills.md": skills_md, "agents.md": agents_md,
    "evaluators.md": evaluators_md, "slots.md": slots_md, "api.md": api_md,
}


def main() -> int:
    check = "--check" in sys.argv
    bad = 0
    for name, fn in FILES.items():
        text = HEADER + fn()
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {name}")
                bad = 1
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    return bad


if __name__ == "__main__":
    raise SystemExit(main())
